def doc(text: str, path: str = "CONTRIBUTING.md") -> PolicyDoc:
    return PolicyDoc(path=path, text=text)


@pytest.mark.parametrize("sentence", BANS)
def test_realistic_bans(sentence: str) -> None:
    result = classify([doc(f"# Contributing\n\nThanks for helping.\n\n{sentence}\n")])
    assert result.status == "banned", sentence
    assert result.ban_path == "CONTRIBUTING.md" and result.ban_line


@pytest.mark.parametrize("sentence", NOT_BANNED)
def test_negations_are_not_bans(sentence: str) -> None:
    assert classify([doc(sentence)]).status != "banned", sentence


def test_allowed() -> None:
    result = classify([doc("AI-assisted contributions are welcome here.")])
    assert result.status == "allowed" and result.allow_path == "CONTRIBUTING.md"


def test_allowed_with_conditions() -> None:
    text = (
        "## AI-assisted contributions\n"
        "AI-assisted pull requests are welcome. You must disclose any AI use in the PR description.\n"
        "Add the `ai-assisted` label to your PR.\n"
        "Prefix the PR title with [AI] when an AI tool wrote code.\n"
        "You must review and understand any AI-generated code you submit.\n"
        "Name the tool and model you used in the pull request.\n"
    )
    result = classify([doc(text)])
    assert result.status == "allowed_with_conditions"
    kinds = {c.kind: c.value for c in result.conditions}
    assert kinds == {"disclosure": "", "label": "ai-assisted", "title_tag": "[AI]", "human_review": "",
                     "tool_named": ""}  # fmt: skip
    assert display(result.status, result.conditions).startswith("allowed with conditions (disclosure")


def test_template_checkbox_condition() -> None:
    template = "## Checklist\n- [ ] Tests added\n- [ ] I have disclosed any AI assistance used for this PR\n"
    result = classify([doc(template, ".github/pull_request_template.md")])
    assert result.status == "allowed_with_conditions"
    box = next(c for c in result.conditions if c.kind == "template_checkbox")
    assert box.value == "I have disclosed any AI assistance used for this PR"


def test_silent_is_unstated() -> None:
    result = classify([doc("# Contributing\nRun the tests before opening a PR.\n"), doc("# Widgets\n", "README.md")])
    assert result.status == "unstated"
    assert display(result.status) == "not stated"


def test_llm_project_readme_alone_stays_unstated() -> None:
    """A README full of LLM wording that never talks about contributions is not an AI policy."""
    readme = "# Tracer\nObservability for LLM apps. Works with any AI framework.\n"
    assert classify([doc(readme, "README.md")]).status == "unstated"


def test_ambiguous_is_unclear() -> None:
    result = classify([doc("We are still discussing an AI policy for contributions in #123.")])
    assert result.status == "unclear"
    assert display(result.status) == "unclear (allowed by your rule)"


def test_maintainer_comment_ban_counts_other_comments_do_not() -> None:
    ban = "We do not accept AI-generated pull requests."
    assert classify([PolicyDoc("issue#1 comment", ban, maintainer=True, kind="issue")]).status == "banned"
    assert classify([PolicyDoc("issue#1 comment", ban, maintainer=False, kind="issue")]).status == "unstated"
    welcome = PolicyDoc("issue#1 comment", "AI PRs are welcome here!", maintainer=True, kind="issue")
    assert classify([welcome]).status == "unstated"  # a maintainer "welcome" is not a doc policy


def test_merge_claim_rules() -> None:
    silent = classify([doc("Run the tests.")])
    allowed = classify([doc("AI-assisted contributions are welcome here.")])
    banned = classify([doc("We do not accept AI-generated pull requests.")])
    texts = ["Run the tests."]
    # an allow claim with a quote that is not in any repo doc can't upgrade
    out = merge_claim(silent, "allowed", ["AI PRs are welcome here, go ahead!"], [], texts)
    assert out.status == "unstated" and not out.llm_upgraded
    # a verified quote upgrades
    texts2 = ["Contributions written with AI assistance are fine by us."]
    out2 = merge_claim(silent, "allowed", ["contributions written  with AI assistance are fine"], [], texts2)
    assert out2.status == "allowed" and out2.llm_upgraded
    # LLM ban beats a deterministic allow; a deterministic ban beats an LLM allow
    assert merge_claim(allowed, "banned", ["no AI please"], [], texts).status == "banned"
    assert merge_claim(banned, "allowed", ["AI-assisted contributions are welcome"], [], texts).status == "banned"
    # LLM-named conditions are added, but can't lift an unstated status without a verified quote
    out3 = merge_claim(silent, "unstated", [], ["human_review", "label"], texts)
    assert out3.status == "unstated" and [c.kind for c in out3.conditions] == ["human_review"]
    out4 = merge_claim(allowed, "allowed", [], ["disclosure"], texts)
    assert out4.status == "allowed_with_conditions"


def test_checklist_round_trip() -> None:
    conds = [
        AiCondition(kind="disclosure"), AiCondition(kind="human_review"), AiCondition(kind="tool_named"),
        AiCondition(kind="label", value="ai-assisted"), AiCondition(kind="title_tag", value="[AI]"),
        AiCondition(kind="template_checkbox", value="I have disclosed any AI assistance"),
    ]  # fmt: skip
    lines = checklist_lines(conds, login="test-bot-login", coder_model="m-coder", reviewer_model="m-review")
    assert len(lines) == 6 and lines[1].startswith("- [x] A human (@test-bot-login)")
    assert "- [ ] Please add the `ai-assisted` label" in lines[3]
    body = "text\n\n" + checklist_block(conds, login="x", coder_model="a", reviewer_model="b")
    title = apply_title_tag("Fix the parser", conds)
    assert title == "[AI] Fix the parser" and apply_title_tag(title, conds) == title
    assert missing_conditions(title, body, conds) == []
    assert missing_conditions("Fix the parser", body, conds) == ["title_tag"]
    assert set(missing_conditions(title, "text", conds)) == {c.kind for c in conds}
    assert checklist_block([], login="x", coder_model="a", reviewer_model="b") == ""
    assert CHECKLIST_HEADER in body


def test_negative_template_box_is_not_ticked() -> None:
    lines = checklist_lines([AiCondition(kind="template_checkbox", value="This PR was not generated with AI")],
                            login="x", coder_model="a", reviewer_model="b")  # fmt: skip
    assert lines == ["- [ ] From the PR template: This PR was not generated with AI"]


def test_sanitizer() -> None:
    assert sanitize_value("ping @maintainer") == ""
    assert sanitize_value("see https://evil.example") == ""
    assert sanitize_value("`ai` <b>label</b>") == "ai blabel/b"
    assert len(sanitize_value("x" * 300)) == 120


def test_parse_conditions_drops_invalid() -> None:
    raw = [{"kind": "label", "value": "ai"}, {"kind": "rm -rf"}, "junk", {"kind": "disclosure", "extra": 1}]
    assert parse_conditions(raw) == (AiCondition(kind="label", value="ai"),)
    assert parse_conditions(None) == ()


def test_display_legacy_and_unknown() -> None:
    assert display("disclosure_required") == "allowed with conditions (disclosure)"
    assert display(None) == "not recorded" and display("allowed") == "allowed"
