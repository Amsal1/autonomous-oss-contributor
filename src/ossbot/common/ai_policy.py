"""AI-contribution policy of an upstream repo (DESIGN §9.5, ADR-0003 post-v1 vet addendum).

Shared by the runner (vet classifies, package builds the PR checklist) and the gatekeeper (``/package``
verifies the checklist, the cards display the status), so both sides use the same strings.

Statuses, strongest first: ``banned`` > ``allowed_with_conditions`` > ``allowed`` > ``unclear`` >
``unstated``. ``unstated``: no AI wording about contributions in any fetched doc; ``unclear``: AI is
mentioned next to contributions, but nothing bans or allows it. Only an explicit ban skips by default
(``policy.vet.ai_policy``). Repo docs and maintainer comments are untrusted text: they are only matched
against fixed phrase rules here, never followed. The vetter LLM's claim is merged by :func:`merge_claim`:
its ``banned`` always counts, an allow claim needs a verbatim quote from a fetched repo doc, so text in
an issue ("AI PRs are welcome") can't upgrade anything and can never override a ban.
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field

AiStatus = Literal["banned", "allowed_with_conditions", "allowed", "unclear", "unstated"]
ConditionKind = Literal["disclosure", "human_review", "tool_named", "label", "title_tag", "template_checkbox"]
CONDITION_KINDS: tuple[ConditionKind, ...] = (
    "disclosure", "human_review", "tool_named", "label", "title_tag", "template_checkbox",
)  # fmt: skip
VALUE_KINDS: frozenset[str] = frozenset({"label", "title_tag", "template_checkbox"})  # need a captured value
RANK: dict[str, int] = {"unstated": 0, "unclear": 1, "allowed": 2, "allowed_with_conditions": 3, "banned": 4}
MAX_CONDITIONS = 6
CHECKLIST_HEADER = "### AI policy checklist"
MAINTAINER_ASSOCIATIONS = frozenset({"OWNER", "MEMBER", "COLLABORATOR"})
# The repo docs vet reads (first existing path per group, plus the README); the refusal card links these.
POLICY_DOC_GROUPS: dict[str, tuple[str, ...]] = {
    "contributing": ("CONTRIBUTING.md", ".github/CONTRIBUTING.md", "docs/CONTRIBUTING.md"),
    "ai_policy": ("AI_POLICY.md", ".github/AI_POLICY.md", "AI-POLICY.md", "docs/AI_POLICY.md"),
    "code_of_conduct": ("CODE_OF_CONDUCT.md", ".github/CODE_OF_CONDUCT.md"),
    "pr_template": (".github/PULL_REQUEST_TEMPLATE.md", ".github/pull_request_template.md",
                    "PULL_REQUEST_TEMPLATE.md", "docs/pull_request_template.md"),
    "support": (".github/SUPPORT.md",),
}  # fmt: skip
POLICY_DOC_PATHS: frozenset[str] = frozenset(p for paths in POLICY_DOC_GROUPS.values() for p in paths)


class AiCondition(BaseModel):
    """A condition the repo puts on AI-assisted contributions; ``value`` is sanitized, never raw."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    kind: ConditionKind
    value: Annotated[str, Field(max_length=120)] = ""
    source: Annotated[str, Field(max_length=200)] = ""


@dataclass(frozen=True)
class PolicyDoc:
    """A fetched text: a repo doc (``kind="doc"``) or an issue body/comment (``kind="issue"``)."""

    path: str
    text: str
    maintainer: bool = False
    kind: Literal["doc", "issue"] = "doc"


@dataclass(frozen=True)
class Classification:
    status: AiStatus
    ban_line: str = ""
    ban_path: str = ""
    allow_line: str = ""
    allow_path: str = ""
    conditions: tuple[AiCondition, ...] = ()
    mentions: int = 0
    llm_upgraded: bool = False
    notes: tuple[str, ...] = field(default=())

    @property
    def source(self) -> str:
        """The doc the status rests on (for the record and the operator; never shown raw on a card)."""
        if self.status == "banned":
            return self.ban_path
        if self.status == "allowed_with_conditions" and self.conditions:
            return self.conditions[0].source or self.allow_path
        return self.allow_path


# ------------------------------------------------------------------------------- phrase rules
# moved from vet.py; post-v1 adds the spelled-out forms (Gentoo/NetBSD wording)
AI_SECTION_RE = re.compile(
    r"\b(AI|LLMs?|generative|Copilot|ChatGPT|Claude|machine[- ]generated|artificial intelligence"
    r"|large language models?)\b",
    re.IGNORECASE,
)
_AI = (
    r"(?:\bAI\b|\bLLMs?\b|large language models?|\bChatGPT\b|\bCopilot\b|generative|\bgen-?AI\b|"
    r"artificial intelligence|machine[- ]generated|\bClaude\b|\bGemini\b|\bCursor\b)"
)
_WORK = r"(?:code|contributions?|PRs?|pull requests?|patch(?:es)?|submissions?|content|changes|commits?|slop|reports?)"
_MADE = r"(?:generated|assisted|written|authored|created|produced)"
# AI-made work: "AI-generated code", "code generated by an LLM", "AI contributions", "contributions from AI"
_AIWORK = (
    rf"(?:{_AI}[- ]{_MADE}|{_MADE}\s+(?:\w+\s+){{0,3}}(?:by|with|using|from)\s+(?:the\s+(?:help|assistance)\s+of\s+)?"
    rf"(?:an?\s+|any\s+)?{_AI}|{_AI}(?:[- ]\w+)?\s+{_WORK}\b|(?:from|by)\s+(?:an?\s+)?{_AI}|\bAI\s+slop\b)"
)
_GAP = r"[^.;!?]{0,60}?"
_I = re.IGNORECASE
BAN_PATTERNS: tuple[re.Pattern[str], ...] = (
    # "We do not accept AI-generated pull requests." / "We don't merge contributions generated by LLMs."
    re.compile(
        rf"\bwe\s+(?:do\s+not|don't|will\s+not|won't|cannot|can't|no\s+longer)\s+(?:accept|merge|allow|take|"
        rf"review|welcome|want)\b{_GAP}{_AIWORK}",
        _I,
    ),
    # "AI-generated code is not accepted" / "LLM-assisted PRs are prohibited" / "... will be closed"
    re.compile(
        rf"{_AI}{_GAP}\b(?:is|are|will\s+be|shall\s+be|get|gets)\s+(?:strictly\s+|expressly\s+|explicitly\s+)?"
        rf"(?:not\s+(?:accepted|allowed|welcome|permitted|tolerated|merged)|prohibited|banned|forbidden|"
        rf"rejected|declined|disallowed|closed)\b",
        _I,
    ),
    # "Do not submit AI-generated code" / "Please don't use ChatGPT or Copilot"
    re.compile(
        rf"\b(?:do\s+not|don't|please\s+do\s+not|please\s+don't|never|must\s+not|may\s+not)\s+(?:submit|open|"
        rf"send|use|contribute|file|create|post)\b{_GAP}{_AI}",
        _I,
    ),
    # "No AI-generated contributions." / "No AI slop." / "No LLM code"
    re.compile(rf"\bno\s+{_AI}(?:[- ]{_MADE})?\s+{_WORK}\b", _I),
    # a sentence that is only "No AI." / "No AI, please" (the legacy ``no ai`` rule, kept narrow)
    re.compile(r"^\W*no\s+(?:AI|LLMs?)\b(?:[\s,]+(?:please|allowed|accepted|contributions))?\W*$", _I),
    # "Contributions written with AI tools will be rejected"
    re.compile(
        rf"\b{_WORK}\s+(?:that\s+(?:are|were|have\s+been)\s+)?{_MADE}\s+(?:by|with|using)\b{_GAP}"
        rf"\b(?:are|is|will\s+be)\s+(?:not\s+(?:accepted|allowed|welcome)|prohibited|banned|rejected|closed|"
        rf"declined)\b",
        _I,
    ),
    # "The use of generative AI tools is not permitted."
    re.compile(
        rf"\buse\s+of\s+(?:\w+\s+){{0,2}}{_AI}{_GAP}\b(?:is|are)\s+(?:strictly\s+)?(?:not\s+(?:permitted|"
        rf"allowed)|prohibited|forbidden|banned)\b",
        _I,
    ),
    # "We will close AI-generated PRs" / "we ban reporters who submit AI slop" / QEMU "DECLINE any
    # contributions which ... derive from AI generated content" / "refrain from including code generated by AI"
    re.compile(rf"\b(?:close|reject|decline|ban|refrain\s+from)\w*\b[^.;!?]{{0,100}}?{_AIWORK}", _I),
    # NetBSD: "Code generated by a large language model ... must not be committed"
    re.compile(
        rf"{_AI}{_GAP}\b(?:must\s+not|may\s+not|cannot|can't|shall\s+not|should\s+not)\s+be\s+(?:contributed|"
        rf"committed|submitted|merged|used|included)\b",
        _I,
    ),
    # NetBSD: "... is presumed to be tainted code"
    re.compile(rf"{_AI}[^.;!?]{{0,200}}?\bpresumed\s+to\s+be\s+tainted\b", _I),
    # Gentoo: "It is expressly forbidden to contribute ... content ... created with the assistance of ... AI tools"
    re.compile(
        rf"\b(?:forbidden|prohibited|not\s+allowed|not\s+permitted)\s+to\s+(?:contribute|submit|commit)\b"
        rf"[^.;!?]{{0,160}}?{_AI}",
        _I,
    ),
)
# a ban phrase in the same sentence as one of these is a condition, not a ban ("don't submit AI code without
# disclosing it"), or a negation ("AI tools are not prohibited")
CONDITIONAL_RE = re.compile(
    r"\b(?:without|unless|except\s+(?:when|if))\b[^.;!?]{0,40}?\b(?:disclos|(?:review|test|understand|verify|"
    r"check)(?:ing|ed)\b|understood|verified|mention|stat(?:e|ing)\b|not(?:e|ing)\b|label|tag|declar|indicat|mark|"
    r"flag|explain)"
    r"|\b(?:don't|do\s+not|doesn't|does\s+not|fail(?:s|ing)?\s+to)\s+(?:disclose|mention|state|declare|indicate|label)",
    _I,
)
NEGATION_RE = re.compile(
    r"\b(?:not|n't|never|no\s+longer)\s+(?:be\s+)?(?:strictly\s+)?(?:prohibited|banned|forbidden|rejected|disallowed)\b"
    r"|\b(?:do|does|will)\s*(?:not|n't)\s+(?:forbid|ban|prohibit|reject|disallow)\b",
    _I,
)
ALLOW_PATTERNS: tuple[re.Pattern[str], ...] = (
    re.compile(
        rf"{_AI}{_GAP}\b(?:are|is)\s+(?:very\s+|always\s+|also\s+|generally\s+)?(?:welcome|allowed|accepted|fine|"
        rf"permitted|ok|okay)\b",
        _I,
    ),
    re.compile(rf"\byou\s+(?:may|can|are\s+(?:welcome|free)\s+to)\s+use\b[^.;!?]{{0,30}}?{_AI}", _I),
    re.compile(rf"\bwe\s+(?:accept|welcome|allow)\b{_GAP}{_AIWORK}", _I),
)
_CONTEXT_RE = re.compile(r"contribut|pull request|\bPRs?\b|patch|submi|commit|merge|code|polic|issue|report", _I)
DISCLOSE_RE = re.compile(
    rf"\b(?:disclos\w*|declar\w*|state|mention|note|indicate|tell\s+us|let\s+us\s+know|be\s+transparent)\b"
    rf"[^.;!?]{{0,80}}?{_AI}|{_AI}[^.;!?]{{0,80}}?\b(?:must|should)\s+be\s+(?:disclosed|declared|stated|mentioned|noted)",
    _I,
)
HUMAN_REVIEW_RE = re.compile(
    r"\b(?:you|the\s+(?:author|contributor|submitter)|a\s+human|contributors?)\s+(?:must|should|are\s+expected\s+to|"
    r"need\s+to)\s+(?:\w+\s+){0,2}(?:review|understand|test|verify|check)\b|\btake\s+(?:full\s+)?responsibility\b"
    r"|\bresponsible\s+for\b",
    _I,
)
TOOL_NAMED_RE = re.compile(r"\b(?:name|specify|list|say|state|mention)\s+(?:\w+\s+){0,2}(?:tools?|models?)\b", _I)
LABEL_RE = re.compile(
    r"\blabel\w*\b[^.;!?`'\"]{0,40}[`'\"]([^`'\"\n]{1,50})[`'\"]|[`'\"]([^`'\"\n]{1,50})[`'\"]\s+label", _I
)
TITLE_TAG_RE = re.compile(r"\btitle\b[^\n]{0,60}?`?(\[[A-Za-z0-9 _:./#-]{1,24}\])`?|`?(\[[A-Za-z0-9 _:./#-]{1,24}\])`?"
                          r"[^\n]{0,60}?\btitle\b", _I)  # fmt: skip
CHECKBOX_RE = re.compile(r"^\s*[-*]\s*\[[ xX]\]\s*(.+)$")
_SENT_SPLIT = re.compile(r"(?<=[.!?])\s+|\n")
_VALUE_OK = re.compile(r"[^A-Za-z0-9 _:./()\[\]#-]")
_TEMPLATE_HINT = re.compile(r"pull_request_template", _I)
_POSITIVE_BOX = re.compile(r"disclos|review|understand|tested|responsib|used|assisted|generated|declar", _I)
_NEGATIVE_BOX = re.compile(r"\b(?:not|no|never|without)\b|n't", _I)


def sanitize_value(text: str) -> str:
    """A repo-derived value (label, tag, checkbox text) safe to put into a PR body: no mention, no URL,
    no markup, ≤ 120 chars; "" when it can't be made safe."""
    if "@" in text or re.search(r"https?:|www\.", text, _I):
        return ""
    clean = re.sub(r"\s+", " ", _VALUE_OK.sub("", text)).strip()
    return clean[:120].strip()


def _sentences(text: str) -> list[str]:
    return [s.strip() for s in _SENT_SPLIT.split(text) if s and s.strip()]


def is_ban(sentence: str) -> bool:
    if NEGATION_RE.search(sentence) or CONDITIONAL_RE.search(sentence):
        return False
    return any(p.search(sentence) for p in BAN_PATTERNS)


def _is_allow(sentence: str) -> bool:
    return (
        not NEGATION_RE.search(sentence)
        and any(p.search(sentence) for p in ALLOW_PATTERNS)
        and not any(p.search(sentence) for p in BAN_PATTERNS)
    )


def _ai_context(line: str) -> bool:
    return bool(AI_SECTION_RE.search(line) and _CONTEXT_RE.search(line))


def _conditions(doc: PolicyDoc) -> list[AiCondition]:
    lines = doc.text.splitlines()
    hits = [i for i, ln in enumerate(lines) if _ai_context(ln) or (AI_SECTION_RE.search(ln) and CHECKBOX_RE.match(ln))]
    window = sorted({j for i in hits for j in (i - 1, i, i + 1) if 0 <= j < len(lines)})
    out: list[AiCondition] = []
    src = doc.path[:200]

    def add(kind: ConditionKind, value: str = "") -> None:
        if kind in VALUE_KINDS and not value:
            return
        cond = AiCondition(kind=kind, value=value, source=src)
        if all((c.kind, c.value) != (cond.kind, cond.value) for c in out):
            out.append(cond)

    for j in window:
        line = lines[j]
        ai_line = bool(AI_SECTION_RE.search(line))
        if DISCLOSE_RE.search(line) and not is_ban(line):
            add("disclosure")
        if HUMAN_REVIEW_RE.search(line):  # lines next to an AI-policy line count (lists under a heading)
            add("human_review")
        if TOOL_NAMED_RE.search(line):
            add("tool_named")
        if (m := LABEL_RE.search(line)) and ai_line:
            add("label", sanitize_value(m.group(1) or m.group(2) or ""))
        if (m := TITLE_TAG_RE.search(line)) and (ai_line or j in hits):
            add("title_tag", sanitize_value(m.group(1) or m.group(2) or ""))
        if _TEMPLATE_HINT.search(doc.path) and ai_line and (m := CHECKBOX_RE.match(line)):
            add("template_checkbox", sanitize_value(m.group(1)))
    return out


def classify(docs: Iterable[PolicyDoc]) -> Classification:
    """The deterministic status over the fetched texts. Issue texts count only when written by a
    maintainer, and only for bans (a maintainer "welcome" can't override a doc ban either)."""
    ban: tuple[str, str] | None = None
    allow: tuple[str, str] | None = None
    conditions: list[AiCondition] = []
    mentions = 0
    for doc in docs:
        if doc.kind == "issue" and not doc.maintainer:
            continue
        for sentence in _sentences(doc.text):
            if not AI_SECTION_RE.search(sentence):
                continue
            if ban is None and is_ban(sentence):
                ban = (sentence, doc.path)
            if doc.kind != "doc":
                continue
            if _ai_context(sentence):
                mentions += 1
            if allow is None and _is_allow(sentence):
                allow = (sentence, doc.path)
        if doc.kind == "doc":
            conditions.extend(c for c in _conditions(doc) if c not in conditions)
    conds = tuple(conditions[:MAX_CONDITIONS])
    if ban is not None:
        return Classification("banned", ban_line=ban[0][:300], ban_path=ban[1][:200], mentions=mentions)
    allow_line, allow_path = (allow[0][:300], allow[1][:200]) if allow else ("", "")
    if conds:
        status: AiStatus = "allowed_with_conditions"
    elif allow:
        status = "allowed"
    else:
        status = "unclear" if mentions else "unstated"
    return Classification(status, allow_line=allow_line, allow_path=allow_path, conditions=conds, mentions=mentions)


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip().lower()


def merge_claim(det: Classification, llm_status: str, llm_evidence_quotes: Sequence[str],
                llm_condition_kinds: Sequence[str], doc_texts: Sequence[str]) -> Classification:  # fmt: skip
    """Merge the vetter's claim (untrusted) into the deterministic result; never weaker than ``det``.

    - a deterministic ban stays a ban; an LLM ``banned`` makes it a ban;
    - ``allowed``/``disclosure_required`` upgrade only if a quote (≥ 20 chars, whitespace-normalized)
      occurs verbatim in a fetched repo doc (``doc_texts``; never the issue or its comments);
    - LLM-named value-less conditions (disclosure, human_review, tool_named) are added as obligations;
      without a verified quote they don't change the status (so they can't lift an ``unstated: skip``).
    """
    if det.status == "banned":
        return det
    quotes = [q for q in llm_evidence_quotes if q and q.strip()]
    if llm_status == "banned":
        line = quotes[0].strip()[:300] if quotes else ""
        return Classification("banned", ban_line=line, ban_path="", mentions=det.mentions, notes=("llm_banned",))
    corpus = [_norm(t) for t in doc_texts if t]
    verified = next((q for q in quotes if len(_norm(q)) >= 20 and any(_norm(q) in t for t in corpus)), None)
    conditions = list(det.conditions)
    for kind in llm_condition_kinds:
        if kind in CONDITION_KINDS and kind not in VALUE_KINDS and all(c.kind != kind for c in conditions):
            conditions.append(AiCondition.model_validate({"kind": kind, "source": "vetter"}))
    if llm_status == "disclosure_required" and all(c.kind != "disclosure" for c in conditions):
        conditions.append(AiCondition(kind="disclosure", source="vetter"))
    status: AiStatus = det.status
    upgraded = False
    if verified is not None and llm_status in {"allowed", "disclosure_required"}:
        claim: AiStatus = "allowed_with_conditions" if llm_status == "disclosure_required" else "allowed"
        if RANK[claim] > RANK[status]:
            status, upgraded = claim, True
    if status == "allowed" and len(conditions) > len(det.conditions):
        status = "allowed_with_conditions"
    return Classification(
        status, allow_line=(verified or det.allow_line)[:300] if upgraded else det.allow_line,
        allow_path=det.allow_path, conditions=tuple(conditions[:MAX_CONDITIONS]), mentions=det.mentions,
        llm_upgraded=upgraded,
    )  # fmt: skip


# ------------------------------------------------------------------------------- PR checklist
def _box(value: str) -> str:
    return "x" if _POSITIVE_BOX.search(value) and not _NEGATIVE_BOX.search(value) else " "


MARKERS: dict[str, str] = {
    "disclosure": "AI assistance is disclosed in the section below.",
    "human_review": "reviewed this change before it was opened and is responsible for it.",
    "tool_named": "Tools used: Kiro CLI",
}


def _marker(cond: AiCondition) -> str:
    if cond.kind == "label":
        return f"Please add the `{cond.value}` label"
    if cond.kind == "title_tag":
        return f"The title carries the `{cond.value}` tag."
    if cond.kind == "template_checkbox":
        return f"From the PR template: {cond.value}"
    return MARKERS[cond.kind]


def checklist_lines(conditions: Sequence[AiCondition], *, login: str, coder_model: str,
                    reviewer_model: str) -> list[str]:  # fmt: skip
    """Fixed sentences per condition (values are sanitized again here); [] when there is nothing to do."""
    out: list[str] = []
    for raw in conditions[:MAX_CONDITIONS]:
        cond = raw.model_copy(update={"value": sanitize_value(raw.value)})
        if cond.kind in VALUE_KINDS and not cond.value:
            continue
        if cond.kind == "disclosure":
            line = f"- [x] {MARKERS['disclosure']}"
        elif cond.kind == "human_review":
            line = f"- [x] A human (@{login}) {MARKERS['human_review']}"
        elif cond.kind == "tool_named":
            line = f"- [x] {MARKERS['tool_named']} (coder model `{coder_model}`, reviewer model `{reviewer_model}`)."
        elif cond.kind == "label":
            line = f"- [ ] {_marker(cond)} (this account cannot set labels)."
        elif cond.kind == "title_tag":
            line = f"- [x] {_marker(cond)}"
        else:
            line = f"- [{_box(cond.value)}] {_marker(cond)}"
        if line not in out:
            out.append(line)
    return out


def checklist_block(conditions: Sequence[AiCondition], *, login: str, coder_model: str, reviewer_model: str) -> str:
    lines = checklist_lines(conditions, login=login, coder_model=coder_model, reviewer_model=reviewer_model)
    return "\n".join([CHECKLIST_HEADER, *lines]) if lines else ""


def apply_title_tag(title: str, conditions: Sequence[AiCondition], max_len: int = 256) -> str:
    """Prefix the title with each recorded title tag once."""
    tags = [t for c in conditions if c.kind == "title_tag" and (t := sanitize_value(c.value))]
    for tag in reversed(list(dict.fromkeys(tags))):
        if tag.lower() not in title.lower():
            title = f"{tag} {title}"
    return title[:max_len]


def missing_conditions(title: str, body: str, conditions: Sequence[AiCondition]) -> list[ConditionKind]:
    """The recorded conditions the title/body don't satisfy (checks the fixed marker text, not models)."""
    out: list[ConditionKind] = []
    for raw in conditions:
        cond = raw.model_copy(update={"value": sanitize_value(raw.value)})
        if cond.kind in VALUE_KINDS and not cond.value:
            continue
        ok = CHECKLIST_HEADER in body and _marker(cond) in body
        if cond.kind == "title_tag":
            ok = ok and cond.value.lower() in title.lower()
        if not ok and cond.kind not in out:
            out.append(cond.kind)
    return out


def parse_conditions(raw: object) -> tuple[AiCondition, ...]:
    """Stored ``ai_conditions`` (a list of dicts) -> validated conditions; invalid entries are dropped."""
    if not isinstance(raw, list):
        return ()
    out: list[AiCondition] = []
    for item in raw[:MAX_CONDITIONS]:
        try:
            out.append(AiCondition.model_validate(item))
        except ValueError:
            continue
    return tuple(out)


# ------------------------------------------------------------------------------------- display
KIND_LABELS: dict[str, str] = {
    "disclosure": "disclosure", "human_review": "human review", "tool_named": "tool named", "label": "label",
    "title_tag": "title tag", "template_checkbox": "template checkbox",
}  # fmt: skip


def normalize_status(stored: object) -> str:
    """A stored ``vetting.ai_policy`` -> a status; legacy ``disclosure_required`` reads as with conditions,
    a missing or unknown value as ``unknown`` (never vetted)."""
    if stored == "disclosure_required":
        return "allowed_with_conditions"
    return str(stored) if stored in RANK else "unknown"


def display(status: object, conditions: Sequence[AiCondition] = ()) -> str:
    """Card text for a stored status (closed set; no repo text)."""
    st = normalize_status(status)
    if st == "allowed_with_conditions":
        kinds = list(dict.fromkeys(KIND_LABELS[c.kind] for c in conditions)) or (
            ["disclosure"] if status == "disclosure_required" else []
        )
        return f"allowed with conditions ({', '.join(kinds)})" if kinds else "allowed with conditions"
    return {
        "allowed": "allowed", "unstated": "not stated", "unclear": "unclear (allowed by your rule)",
        "banned": "banned",
    }.get(st, "not recorded")  # fmt: skip
